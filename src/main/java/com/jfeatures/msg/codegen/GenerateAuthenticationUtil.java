package com.jfeatures.msg.codegen;

import com.jfeatures.msg.codegen.util.JavaPackageNameBuilder;
import com.squareup.javapoet.ClassName;
import com.squareup.javapoet.CodeBlock;
import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.TypeSpec;
import io.jsonwebtoken.Claims;
import io.jsonwebtoken.Jwts;
import jakarta.servlet.http.HttpServletRequest;
import lombok.extern.slf4j.Slf4j;

import javax.lang.model.element.Modifier;
import java.io.IOException;

/**
 * Generates authentication utility class for extracting user identity from requests.
 * Follows Vipin's Principle: Single responsibility - authentication utility generation only.
 */
@Slf4j
public class GenerateAuthenticationUtil {

    private static final String CLASS_NAME = "AuthenticationUtil";
    private static final String PACKAGE_SUFFIX = "util";

    private GenerateAuthenticationUtil() {
        throw new UnsupportedOperationException("Utility class");
    }

    /**
     * Creates AuthenticationUtil class for extracting user ID from requests.
     * Supports JWT tokens (primary) and HTTP headers (fallback).
     */
    public static JavaFile createAuthenticationUtil(String businessPurposeOfSQL) throws IOException {

        // Method: getUserId(HttpServletRequest request)
        MethodSpec getUserIdMethod = createGetUserIdMethod();

        // Method: extractUserIdFromJwt(String token)
        MethodSpec extractFromJwtMethod = createExtractFromJwtMethod();

        // Method: extractUserIdFromHeader(HttpServletRequest request)
        MethodSpec extractFromHeaderMethod = createExtractFromHeaderMethod();

        // AuthenticationUtil class
        TypeSpec authUtil = TypeSpec.classBuilder(CLASS_NAME)
                .addModifiers(Modifier.PUBLIC)
                .addMethod(getUserIdMethod)
                .addMethod(extractFromJwtMethod)
                .addMethod(extractFromHeaderMethod)
                .addJavadoc("Utility class for extracting authenticated user identity from HTTP requests.\n" +
                           "Supports JWT token extraction (primary method) and HTTP header fallback.\n" +
                           "Generated by MSG - Microservice Generator.")
                .build();

        JavaFile javaFile = JavaFile.builder(JavaPackageNameBuilder.buildJavaPackageName(businessPurposeOfSQL, PACKAGE_SUFFIX), authUtil)
                .build();

        log.info(javaFile.toString());
        return javaFile;
    }

    /**
     * Creates main getUserId method that tries JWT first, then header fallback.
     */
    private static MethodSpec createGetUserIdMethod() {
        CodeBlock methodBody = CodeBlock.builder()
                .addStatement("$T authHeader = request.getHeader(\"Authorization\")", String.class)
                .add("\n")
                .beginControlFlow("if (authHeader != null && authHeader.startsWith(\"Bearer \"))")
                .addStatement("$T token = authHeader.substring(7)", String.class)
                .addStatement("$T userIdFromJwt = extractUserIdFromJwt(token)", String.class)
                .beginControlFlow("if (userIdFromJwt != null)")
                .addStatement("return userIdFromJwt")
                .endControlFlow()
                .endControlFlow()
                .add("\n")
                .addStatement("return extractUserIdFromHeader(request)")
                .build();

        return MethodSpec.methodBuilder("getUserId")
                .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
                .addParameter(HttpServletRequest.class, "request")
                .returns(String.class)
                .addCode(methodBody)
                .addJavadoc("Extract user ID from HTTP request.\n" +
                           "Tries JWT token extraction first, falls back to X-User-Id header.\n" +
                           "@param request HTTP servlet request\n" +
                           "@return User ID string, or \"system\" if not found")
                .build();
    }

    /**
     * Creates method to extract user ID from JWT token.
     */
    private static MethodSpec createExtractFromJwtMethod() {
        CodeBlock methodBody = CodeBlock.builder()
                .beginControlFlow("try")
                .add("// Parse JWT token without signature verification (for demo/dev purposes)\n")
                .add("// In production, use proper secret key: Jwts.parserBuilder().setSigningKey(key).build()\n")
                .addStatement("int lastDotIndex = token.lastIndexOf('.')")
                .beginControlFlow("if (lastDotIndex > 0)")
                .addStatement("$T tokenWithoutSignature = token.substring(0, lastDotIndex + 1)", String.class)
                .addStatement("$T claims = $T.parserBuilder().build().parseClaimsJwt(tokenWithoutSignature).getBody()",
                        Claims.class, Jwts.class)
                .add("\n")
                .add("// Try common claim names for user ID\n")
                .addStatement("$T userId = claims.get(\"userId\", $T.class)", String.class, String.class)
                .beginControlFlow("if (userId != null)")
                .addStatement("return userId")
                .endControlFlow()
                .add("\n")
                .addStatement("userId = claims.get(\"sub\", $T.class)", String.class)
                .beginControlFlow("if (userId != null)")
                .addStatement("return userId")
                .endControlFlow()
                .add("\n")
                .addStatement("userId = claims.get(\"user_id\", $T.class)", String.class)
                .beginControlFlow("if (userId != null)")
                .addStatement("return userId")
                .endControlFlow()
                .endControlFlow()
                .nextControlFlow("catch ($T e)", Exception.class)
                .add("// JWT parsing failed, return null to try fallback methods\n")
                .addStatement("return null")
                .endControlFlow()
                .add("\n")
                .addStatement("return null")
                .build();

        return MethodSpec.methodBuilder("extractUserIdFromJwt")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .addParameter(String.class, "token")
                .returns(String.class)
                .addCode(methodBody)
                .addJavadoc("Extract user ID from JWT token claims.\n" +
                           "Tries multiple common claim names: userId, sub, user_id.\n" +
                           "@param token JWT token string\n" +
                           "@return User ID if found, null otherwise")
                .build();
    }

    /**
     * Creates method to extract user ID from HTTP header (fallback).
     */
    private static MethodSpec createExtractFromHeaderMethod() {
        CodeBlock methodBody = CodeBlock.builder()
                .addStatement("$T userId = request.getHeader(\"X-User-Id\")", String.class)
                .beginControlFlow("if (userId != null && !userId.trim().isEmpty())")
                .addStatement("return userId.trim()")
                .endControlFlow()
                .add("\n")
                .add("// Default to 'system' if no user identification found\n")
                .addStatement("return \"system\"")
                .build();

        return MethodSpec.methodBuilder("extractUserIdFromHeader")
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .addParameter(HttpServletRequest.class, "request")
                .returns(String.class)
                .addCode(methodBody)
                .addJavadoc("Extract user ID from X-User-Id HTTP header (fallback method).\n" +
                           "@param request HTTP servlet request\n" +
                           "@return User ID from header, or \"system\" as default")
                .build();
    }
}
